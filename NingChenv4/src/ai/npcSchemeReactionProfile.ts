import type { NPC, SchemeType } from '../game/types'
import { getNpcVoiceProfile } from '../game/npcVoiceProfile'

type NpcReactionRole = 'court' | 'external' | 'hybrid_external'

const PRESSURE_SCHEMES = new Set<SchemeType>([
    'slander',
    'alienate',
    'frame',
    'proxy',
    'omen',
    'secession',
    'rebellion',
])

function joinReactionMatrix(lines: string[]): string {
    return ['反应矩阵：', ...lines.map(line => `- ${line}`)].join('\n')
}

function joinPressureOverlay(lines: string[]): string {
    return ['高压叠加：', ...lines.map(line => `- ${line}`)].join('\n')
}

export function getNpcReactionRole(npc: Pick<NPC, 'id' | 'powerBase'>): NpcReactionRole {
    if (npc.id === 'duguwenyue') {
        return 'hybrid_external'
    }
    return npc.powerBase === 'external' ? 'external' : 'court'
}

export function describeNpcPressureOverlay(params: {
    npc: NPC
    schemeType: SchemeType
    success: boolean
}): string {
    if (!PRESSURE_SCHEMES.has(params.schemeType)) {
        return ''
    }

    const profile = getNpcVoiceProfile(params.npc)

    return joinPressureOverlay([
        '这类计谋属于高压场景，反应矩阵定方向，声音档案里的“高压偏移”定质感。',
        params.success
            ? '这一步若已得手，人物的惊疑、怒意、自辩或盘算，都要先顺着当回合反应方向，再压成他本人的高压质感。'
            : '这一步若未成或被识破，人物的收口、反刺、记账与压人方式，也要先顺着当回合反应方向，再压成他本人的高压质感。',
        `当前人物的高压偏移：${profile.pressureShift}`,
    ])
}

