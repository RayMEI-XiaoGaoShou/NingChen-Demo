// ========================================
// Fallback 调度
// ========================================

export function getFallbackResponse(tag?: string): string {
    if (!tag) return randomPick(GENERIC_FALLBACKS)

    // 天道判官
    if (tag === 'judge') return randomPick(JUDGE_FALLBACKS)

    // NPC 反馈
    if (tag.startsWith('npc_')) {
        const key = tag.replace('npc_', '')
        const responses = NPC_FEEDBACK[key]
        if (responses) return randomPick(responses)
        return randomPick(GENERIC_FALLBACKS)
    }

    if (tag === 'empress_feedback') return randomPick(EMPRESS_FEEDBACK_FALLBACKS)

    return randomPick(GENERIC_FALLBACKS)
}

export function getFallbackEmpressQuestion(): {
    question: string
    options: string[]
} {
    const q = randomPick(EMPRESS_FALLBACK_QUESTIONS)
    return { question: q.question, options: q.options }
}

function randomPick<T>(arr: T[]): T {
    return arr[Math.floor(Math.random() * arr.length)]
}
