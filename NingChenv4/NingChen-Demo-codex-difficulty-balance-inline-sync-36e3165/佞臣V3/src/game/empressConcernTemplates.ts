export function getEmpressConcernTemplate(round: number): EmpressConcernTemplate {
    return EMPRESS_CONCERN_TEMPLATES.find(item => item.round === round) ?? DEFAULT_CONCERN
}

export function adjustConcernOpeningForSafety(opening: string, stage: PlayerDangerStage): string {
    if (stage !== 'under_review') return opening

    return opening
        .replace(/阿颖[，,]/g, '')
        .replace(/宝颖[，,]/g, '')
        .replace(/，阿颖/g, '')
        .replace(/，宝颖/g, '')
        .replace(/阿颖/g, '你')
        .replace(/宝颖/g, '你')
}

export function getPlayerDangerConcernOverlay(stage: PlayerDangerStage): string {
    if (stage === 'under_review') {
        return '密札往来隔着数重人手，每一句都可能被截读。回信应更短、更稳，不明写北边细节，不出现私人称呼（不用“阿颖”），不把姐弟关系说满。起笔也要压短，像公文多过像家书。'
    }
    if (stage === 'under_watch') {
        return '近来书信辗转日久，有些字句似被人动过。回信应半是提醒、半是寄望，起笔不宜太私人，收束语气要收紧。不要写出“朕知你被盯上”这种直接信息。'
    }
    return '密札安全，起笔可写得从容些，允许出现私人情感和回忆。收束仍要提醒萧宝颖不可大意，但语气可以稍松。'
}
